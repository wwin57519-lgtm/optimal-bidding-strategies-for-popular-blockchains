const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const solc = require('./evm/node_modules/solc');
const ganache = require('./evm/node_modules/ganache');
const { ethers } = require('./evm/node_modules/ethers');

async function main() {
  const input = {language:'Solidity', sources:Object.fromEntries(['FixedPoolLaunchBuyer.sol','MockLaunch.sol'].map(name =>
    [name,{content:fs.readFileSync(path.join(__dirname,name),'utf8')}])) , settings:{optimizer:{enabled:true,runs:200},viaIR:true,evmVersion:'shanghai',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object']}}}};
  const output=JSON.parse(solc.compile(JSON.stringify(input)));
  const errors=(output.errors||[]).filter(x=>x.severity==='error');
  assert.equal(errors.length,0,JSON.stringify(errors));
  const compiled=output.contracts['FixedPoolLaunchBuyer.sol'].FixedPoolLaunchBuyer;
  fs.writeFileSync(path.join(__dirname,'compiled_reference.json'),JSON.stringify({compiler:solc.version(),evm_version:'shanghai',abi:compiled.abi,bytecode:compiled.evm.bytecode.object,runtime_bytes:compiled.evm.deployedBytecode.object.length/2},null,2));
  const rpc=ganache.provider({logging:{quiet:true},wallet:{totalAccounts:55},chain:{chainId:8453,hardfork:'shanghai'}});
  const provider=new ethers.BrowserProvider(rpc); provider.pollingInterval=25;
  const signers=await Promise.all(Array.from({length:55},(_,i)=>provider.getSigner(i)));
  const addresses=await Promise.all(signers.map(x=>x.getAddress()));
  const deploy=async(source,name,args=[])=>{
    const artifact=output.contracts[source][name];
    const c=await new ethers.ContractFactory(artifact.abi,artifact.evm.bytecode.object,signers[0]).deploy(...args);
    await c.waitForDeployment(); return c;
  };
  const payment=await deploy('MockLaunch.sol','MockToken');
  const target=await deploy('MockLaunch.sol','MockToken');
  const pool=await deploy('MockLaunch.sol','MockPool',[addresses[0],await payment.getAddress(),await target.getAddress()]);
  await (await target.mint(await pool.getAddress(),ethers.parseEther('1000000'))).wait();
  const block=await provider.getBlock('latest');
  const makeBuyer=async(overrides={})=>{
    const args=[await pool.getAddress(),addresses[0],await payment.getAddress(),await target.getAddress(),addresses[54],100000000n,ethers.parseEther('1000'),block.timestamp-1,block.timestamp+600,4295128740n,addresses.slice(1,51)];
    for (const [k,v] of Object.entries(overrides)) args[Number(k)]=v;
    const buyer=await deploy('FixedPoolLaunchBuyer.sol','FixedPoolLaunchBuyer',args);
    await (await payment.mint(await buyer.getAddress(),100000000n)).wait();
    return buyer;
  };
  const buyer=await makeBuyer();
  const tests=[]; const gas={};
  const fail=async(name,fn)=>{let error;try{const t=await fn();await t.wait();}catch(e){error=e;}assert.ok(error,name);assert.equal(error.receipt?.status,0,name);tests.push({name,status:'passed'});return Number(error.receipt.gasUsed);};
  const nonceBefore=BigInt(await rpc.request({method:'eth_getTransactionCount',params:[addresses[1],'latest']}));
  gas.before_open=await fail('zero liquidity reverts without buying',()=>buyer.connect(signers[1]).buy({gasLimit:1000000}));
  const nonceAfter=BigInt(await rpc.request({method:'eth_getTransactionCount',params:[addresses[1],'latest']}));
  assert.equal(nonceAfter,nonceBefore+1n);tests.push({name:'included reverted attempt consumes its EOA nonce',status:'passed'});
  assert.equal(await buyer.bought(),false);
  await fail('unauthorized trigger rejected',()=>buyer.connect(signers[52]).buy({gasLimit:1000000}));
  await fail('forged callback rejected',()=>buyer.connect(signers[1]).uniswapV3SwapCallback(1,0,'0x',{gasLimit:1000000}));
  await (await pool.setLiquidity(1)).wait();
  await (await pool.setOutput(ethers.parseEther('900'))).wait();
  gas.min_output_revert=await fail('insufficient output rolls back balances and success flag',()=>buyer.connect(signers[1]).buy({gasLimit:1000000}));
  assert.equal(await buyer.bought(),false);assert.equal(await payment.balanceOf(await buyer.getAddress()),100000000n);assert.equal(await target.balanceOf(addresses[54]),0n);
  await (await pool.setOutput(ethers.parseEther('1200'))).wait();
  await (await target.setTax(2000)).wait();
  await fail('actual recipient balance detects output transfer tax',()=>buyer.connect(signers[1]).buy({gasLimit:1000000}));
  await (await target.setTax(0)).wait();
  await (await pool.setPaymentBps(5000)).wait();
  await fail('partial exact-input payment rejected atomically',()=>buyer.connect(signers[1]).buy({gasLimit:1000000}));
  await (await pool.setPaymentBps(10000)).wait();
  const success=await (await buyer.connect(signers[1]).buy({gasLimit:1000000})).wait();
  gas.success=Number(success.gasUsed);assert.equal(success.status,1);assert.equal(await buyer.bought(),true);
  assert.equal(await target.balanceOf(addresses[54]),ethers.parseEther('1200'));assert.equal(await payment.balanceOf(await buyer.getAddress()),0n);
  tests.push({name:'successful purchase pays exactly once and reaches fixed recipient',status:'passed'});
  gas.after_success=await fail('second wallet cannot purchase again',()=>buyer.connect(signers[2]).buy({gasLimit:1000000}));
  const cancelled=await makeBuyer();await (await cancelled.cancel()).wait();
  await fail('owner cancellation stops subsequent attempts',()=>cancelled.connect(signers[3]).buy({gasLimit:1000000}));
  await fail('keeper cannot withdraw contract funds',async()=>cancelled.connect(signers[3]).rescue(await payment.getAddress(),1,{gasLimit:1000000}));
  let wrongFactory=false;try{await makeBuyer({1:addresses[53]});}catch{wrongFactory=true;}assert.ok(wrongFactory);tests.push({name:'constructor rejects wrong factory',status:'passed'});
  const race=await makeBuyer();
  const attempts=await Promise.all(signers.slice(1,51).map(s=>race.connect(s).buy({gasLimit:1000000})));
  const raceReceipts=await Promise.all(attempts.map(async t=>{try{return await t.wait();}catch(e){assert.ok(e.receipt);return e.receipt;}}));
  assert.equal(raceReceipts.filter(r=>r.status===1).length,1);
  assert.equal(raceReceipts.filter(r=>r.status===0).length,49);
  tests.push({name:'50 wallet triggers result in exactly one successful shared purchase',status:'passed'});
  const expiring=await makeBuyer();await rpc.request({method:'evm_increaseTime',params:[1000]});await rpc.request({method:'evm_mine',params:[]});
  await fail('expired window rejects purchase',()=>expiring.connect(signers[4]).buy({gasLimit:1000000}));
  const report={status:'passed',compiler:solc.version(),chain_id:8453,environment:'local in-memory Ganache with mock token and pool; not Base mainnet or historical fork',tests,gas_used_mock_only:gas,multi_wallet_lock:{triggers:50,successes:1,reverted:49,meaning:'one-success state invariant only; not a sequencing benchmark'},runtime_bytes:compiled.evm.deployedBytecode.object.length/2,claims_not_validated:['historical pool compatibility','pre-82 successful swap gas','live inclusion latency','first-buy win rate']};
  fs.writeFileSync(path.join(__dirname,'contract_test_report.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify({status:'passed',tests:tests.length,gas_used_mock_only:gas,runtime_bytes:report.runtime_bytes}));
  await rpc.disconnect();
}
main().catch(e=>{console.error(e.message);process.exitCode=1;});
